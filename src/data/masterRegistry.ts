/**
 * Match an applicant or document against the 100-record National Reference Database
 */
export function findMatchingMasterRecord(query: {
  fullName?: string;
  fatherName?: string;
  uniqueId?: string;
  certNumber?: string;
  bankAccount?: string;
}): MasterRecord | undefined {
  const cleanStr = (s?: string) => s?.toLowerCase().replace(/[^a-z0-9]/g, '') || '';
  const qName = cleanStr(query.fullName);
  const qFather = cleanStr(query.fatherName);
  const qUid = cleanStr(query.uniqueId);
  const qCert = cleanStr(query.certNumber);
  const qBank = cleanStr(query.bankAccount);

  return MASTER_REGISTRY_DATA.find((rec) => {
    // Exact unique ID match
    if (qUid && cleanStr(rec.unique_id_number) === qUid) return true;

    // Certificate number match
    if (qCert && cleanStr(rec.category_certificate_number) === qCert) return true;

    // Bank account match
    if (qBank && cleanStr(rec.bank_account_number) === qBank) return true;

    // Full name match
    if (qName && cleanStr(rec.full_name) === qName) return true;

    // Name + Father's Name fuzzy combo
    if (qName && qFather && cleanStr(rec.full_name).includes(qName) && cleanStr(rec.fathers_name).includes(qFather)) {
      return true;
    }

    return false;
  });
}
